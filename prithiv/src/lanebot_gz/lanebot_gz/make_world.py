"""Write the Gazebo world: ground, the oval road with markings, and our car."""
import math
import os
import sys

from lanebot_gz import track

W = track.LANE_WIDTH
SEG = 2.0   # m, length of each road piece in the bends


def box(name, x, y, yaw, length, width, height, z, colour):
    r, g, b = colour
    return f"""
        <visual name="{name}">
          <pose>{x:.3f} {y:.3f} {z:.3f} 0 0 {yaw:.4f}</pose>
          <geometry><box><size>{length:.3f} {width:.3f} {height:.3f}</size></box></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material>
        </visual>"""


def road_visuals():
    """Asphalt, solid edge lines and a dashed line between the two lanes."""
    out = []
    asphalt = (0.15, 0.15, 0.15)
    white = (0.95, 0.95, 0.95)
    n = int(track.LENGTH // SEG)
    for i in range(n):
        s = (i + 0.5) * SEG
        # asphalt: from 1.75 m right of our lane centre to 5.25 m left of it
        x, y, yaw = track.shifted(s, W / 2)
        out.append(box(f'asphalt_{i}', x, y, yaw, SEG + 0.05, 2 * W, 0.02, 0.01, asphalt))
        for side, lat in (('right', -W / 2), ('left', 1.5 * W)):
            x, y, yaw = track.shifted(s, lat)
            out.append(box(f'edge_{side}_{i}', x, y, yaw, SEG + 0.05, 0.15, 0.01, 0.025, white))
        if i % 3 == 0:   # dashes: 2 m line, 4 m gap
            x, y, yaw = track.shifted(s, W / 2)
            out.append(box(f'dash_{i}', x, y, yaw, SEG, 0.15, 0.01, 0.025, white))
    return ''.join(out)


