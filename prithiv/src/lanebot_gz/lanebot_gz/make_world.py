def wheels():
    out = []
    for name, x, y in (('fl', 1.45, 0.85), ('fr', 1.45, -0.85), ('rl', -1.45, 0.85), ('rr', -1.45, -0.85)):
        out.append(f"""
        <visual name="wheel_{name}">
          <pose>{x} {y} 0.35 1.5708 0 0</pose>
          <geometry><cylinder><radius>0.35</radius><length>0.25</length></cylinder></geometry>
          <material><ambient>0.05 0.05 0.05 1</ambient><diffuse>0.05 0.05 0.05 1</diffuse></material>
        </visual>""")
    return ''.join(out)


def world():
    return f"""<?xml version="1.0"?>
<!-- Generated by make_world.py; edit that file, not this one. -->
<sdf version="1.9">
  <world name="lanebot">
    <physics name="default" type="ignored"><max_step_size>0.01</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 50 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <direction>-0.4 0.2 -0.9</direction>
    </light>
    <scene><ambient>0.5 0.5 0.5 1</ambient><background>0.6 0.75 0.9 1</background></scene>

    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>800 800</size></plane></geometry></collision>
        <visual name="grass">
          <pose>75 60 0 0 0 0</pose>
          <geometry><plane><normal>0 0 1</normal><size>800 800</size></plane></geometry>
          <material><ambient>0.25 0.45 0.2 1</ambient><diffuse>0.25 0.45 0.2 1</diffuse></material>
        </visual>
      </link>
    </model>

    <model name="road">
      <static>true</static>
      <link name="link">{road_visuals()}
      </link>
    </model>
{CAR.replace('WHEELS', wheels())}
  </world>
</sdf>
"""


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else 'lanebot.sdf'
    with open(path, 'w') as f:
        f.write(world())
    print(f'Wrote {os.path.abspath(path)}  (track length {track.LENGTH:.0f} m)')


if __name__ == '__main__':
    main()
